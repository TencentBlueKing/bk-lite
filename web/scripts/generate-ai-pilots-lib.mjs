import fs from 'node:fs';
import path from 'node:path';

export const HEADER = `/* Generated by scripts/generate-ai-pilots.mjs -- DO NOT EDIT BY HAND */\n`;

/**
 * Derive a pathname prefix from a pilot file path under src/app.
 * Example: monitor/(pages)/view/dashboard/dashboard.pilot.ts -> /monitor/view/dashboard/
 */
export const pathnamePrefixFromPilotFile = (relativePosix) => {
  const normalized = relativePosix.replace(/\\/g, '/').replace(/^\/+/, '');
  const withoutExt = normalized.replace(/\.pilot\.tsx?$/i, '');
  const parts = withoutExt.split('/').filter(Boolean);
  // Drop route groups and dynamic [param] segments from the prefix.
  const dirs = parts
    .slice(0, -1)
    .filter((part) => !/^\([^)]+\)$/.test(part) && !/^\[[^\]]+\]$/.test(part));
  if (!dirs.length) return '/';
  return `/${dirs.join('/')}/`;
};

export const walkPilots = (dir, acc = []) => {
  if (!fs.existsSync(dir)) return acc;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walkPilots(full, acc);
      continue;
    }
    if (/\.pilot\.tsx?$/i.test(entry.name)) acc.push(full);
  }
  return acc;
};

export const toImportPath = (absoluteFile, rootDir) => {
  const rel = path.relative(path.join(rootDir, 'src'), absoluteFile).replace(/\\/g, '/');
  const withoutExt = rel.replace(/\.tsx?$/i, '');
  return `@/${withoutExt}`;
};

export const emptyManifest = () =>
  `${HEADER}import type { AiPageContextPilot } from './types';\n\nexport const GENERATED_PAGE_CONTEXT_PILOTS: AiPageContextPilot[] = [];\n`;

export const buildPilotsManifestSource = (pilotFiles, webRootDir) => {
  const sorted = [...pilotFiles].sort((a, b) => a.localeCompare(b));
  if (!sorted.length) return emptyManifest();

  const entries = sorted.map((file) => {
    const relFromApp = path.relative(path.join(webRootDir, 'src', 'app'), file).replace(/\\/g, '/');
    const prefix = pathnamePrefixFromPilotFile(relFromApp);
    const importPath = toImportPath(file, webRootDir);
    return { prefix, importPath };
  });

  const lines = [
    HEADER.trimEnd(),
    `import type { AiPageContextPilot } from './types';`,
    '',
    'export const GENERATED_PAGE_CONTEXT_PILOTS: AiPageContextPilot[] = [',
  ];
  for (const entry of entries) {
    lines.push('  {');
    lines.push(`    test: (pathname) => pathname.includes('${entry.prefix}'),`);
    lines.push(`    load: () => import('${entry.importPath}'),`);
    lines.push('  },');
  }
  lines.push('];');
  lines.push('');
  return `${lines.join('\n')}\n`;
};

export const writeIfChanged = (file, content) => {
  if (fs.existsSync(file)) {
    const prev = fs.readFileSync(file, 'utf8');
    if (prev === content) return false;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, 'utf8');
  return true;
};
