import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const fields = JSON.parse(fs.readFileSync(path.join(root, 'server/apps/alerts/utils/rule_fields.json'), 'utf8'));
const output = path.join(root, 'web/src/app/alarm/constants/rule-fields.generated.ts');
const content = '// Generated by scripts/generate-alarm-rule-fields.mjs; edit server/apps/alerts/utils/rule_fields.json.\n'
  + `export const RULE_FIELDS = ${JSON.stringify(fields, null, 2)} as const;\n`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== content) throw new Error('告警规则字段目录未同步');
} else fs.writeFileSync(output, content);
