const legacyThemeIds: Record<string, ScreenThemeId> = {
  'screen-tech-blue': 'screen-dark',
  'screen-glass-light': 'screen-light',
};

export const SCREEN_THEME_OPTIONS = Object.values(screenThemeDefinitions);

export const resolveScreenThemeId = (
  theme?: string,
): ScreenThemeId => {
  if (theme && theme in screenThemeDefinitions) {
    return theme as ScreenThemeId;
  }
  return (theme && legacyThemeIds[theme]) || DEFAULT_SCREEN_THEME_ID;
};

export const getScreenTheme = (
  theme?: string,
): ScreenThemeDefinition => screenThemeDefinitions[resolveScreenThemeId(theme)];
